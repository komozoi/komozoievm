class TestStateProvider: public StateProvider {
public:

	TestStateProvider()
		: accounts(16), runcodes(16), storage(16) {}

	// Account information
	EthereumAccountInfo getAccountInfo(const EthereumAddress& address, uint64_t blockNumber) override {
		EthereumAccountInfo* info = accounts.getPtr(address);
		if (!info)
			return EthereumAccountInfo(address, uint256_t("0xde0b6b3a7640000"));
		return *info;
	}

	Bytes getContractCode(const EthereumAddress& address) override {
		Bytes* runcode = runcodes.getPtr(address);
		if (!runcode)
			return {};
		return *runcode;
	}

	ArrayList<uint256_t> getStorageSlots(const EthereumAddress& address, const ArrayList<LongKey<256>> &slotKeys,
										 uint64_t blockNumber) override {
		HashMap<LongKey<256>, uint256_t>* slots = storage.getOrDefault(address, nullptr);
		if (!slots)
			slots = storage.put(address, new HashMap<LongKey<256>, uint256_t>(16));

		ArrayList<uint256_t> out(slotKeys.size());
		for (int i = 0; i < slotKeys.size(); i++) {
			LongKey<256>& key = slotKeys.get(i);
			uint256_t* value = slots->getPtr(key);
			if (!value)
				value = &slots->put(key, uint256_t());
			out.add(*value);
		}

		return out;
	}

	// Updates to internal/tracked state
	bool updateAccount(const EthereumAddress& address, const EthereumAccountInfo& account) override {
		accounts.put(address, account);
		return true;
	}

	bool saveContractCode(const EthereumAddress& address, Bytes runcode) override {
		runcodes.put(address, runcode);
		return true;
	}

	bool updateStorageSlots(const EthereumAddress& address, const HashMap<LongKey<256>, uint256_t>& entries) override {
		HashMap<LongKey<256>, uint256_t>* dst = storage.getOrDefault(address, nullptr);
		if (dst)
			dst->putFrom(entries);
		else
			storage.put(address, new HashMap(entries));
		return true;
	}

	HashMap<EthereumAddress, EthereumAccountInfo> accounts;
	HashMap<EthereumAddress, Bytes> runcodes;
	HashMap<EthereumAddress, HashMap<LongKey<256>, uint256_t>*> storage;
};


