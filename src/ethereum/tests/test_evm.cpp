TEST(EVMTest, TestDivByOne) {
	// PUSH1 1 (denominator)
	// PUSH32 2^64 + 1 (numerator)
	// DIV
	// PUSH0
	// MSTORE
	// PUSH1 32
	// PUSH0
	// RETURN
	const uint8_t code[] = {
			0x60, 0x01,
			0x7f, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
			      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
			0x04,
			0x5f,
			0x52,
			0x60, 0x20,
			0x5f,
			0xf3
	};

	tmp_sim_output_t out = simulate(code, sizeof(code));

	EXPECT_TRUE(out.output.success) << out.output.reason;
	EXPECT_EQ(out.output.returnData.size(), 32);

	const uint8_t expected[] = {
			0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
			0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00
	};

	for (int i = 0; i < 32; i++) {
		EXPECT_EQ(out.output.returnData.get(i), expected[i]) << "Mismatch at byte " << i;
	}
}

